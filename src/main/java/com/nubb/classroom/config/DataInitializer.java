package com.nubb.classroom.config;

import com.nubb.classroom.repository.AccountRepository;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;

@Configuration
public class DataInitializer {

    @Bean
    public CommandLineRunner initData(AccountRepository accountRepository, DataSource dataSource) {
        return args -> {
            // 1. Schema migration: Ensure active and profile columns exist in account table
            try (Connection conn = dataSource.getConnection();
                 Statement stmt = conn.createStatement()) {
                stmt.execute("ALTER TABLE IF EXISTS \"ACCOUNT\" ADD COLUMN IF NOT EXISTS \"ACTIVE\" BOOLEAN DEFAULT TRUE");
                stmt.execute("ALTER TABLE IF EXISTS account ADD COLUMN IF NOT EXISTS active BOOLEAN DEFAULT TRUE");
                stmt.execute("UPDATE account SET active = TRUE WHERE active IS NULL");
                stmt.execute("ALTER TABLE IF EXISTS exam ALTER COLUMN class_name SET DATA TYPE VARCHAR(1000)");
                String createCertTable = "CREATE TABLE IF NOT EXISTS \"PUBLIC\".\"CERTIFICATE_RECORDS\"(" +
                        "\"ID\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, " +
                        "\"STUDENT_ID\" BIGINT NOT NULL, " +
                        "\"CLASS_NAME\" VARCHAR(100), " +
                        "\"SERIAL_NUMBER\" VARCHAR(255) UNIQUE, " +
                        "\"SCHOOL_NAME\" VARCHAR(500), " +
                        "\"SUBJECT_NAME\" VARCHAR(255), " +
                        "\"PROVINCE\" VARCHAR(255), " +
                        "\"TEACHER_NAME\" VARCHAR(255), " +
                        "\"ROLE_SIGNER_LEFT\" VARCHAR(255), " +
                        "\"ROLE_SIGNER_RIGHT\" VARCHAR(255), " +
                        "\"ISSUE_DATE_KHMER\" VARCHAR(255), " +
                        "\"ISSUE_DATE_EN\" VARCHAR(255), " +
                        "\"UPDATED_AT\" TIMESTAMP)";
                try { stmt.execute(createCertTable); } catch (Exception ignored) {}


                String[] profileCols = {
                    "GENDER VARCHAR(255)",
                    "SCHOOL_NAME VARCHAR(255)",
                    "SUBJECT VARCHAR(255)",
                    "PROVINCE VARCHAR(255)",
                    "PHONE VARCHAR(255)",
                    "TELEGRAM VARCHAR(255)",
                    "EMAIL VARCHAR(255)",
                    "POSITION VARCHAR(255)",
                    "TEACHING_CLASSES VARCHAR(255)",
                    "BIO VARCHAR(1000)"
                };
                for (String col : profileCols) {
                    try { stmt.execute("ALTER TABLE IF EXISTS \"ACCOUNT\" ADD COLUMN IF NOT EXISTS " + col); } catch (Exception ignored) {}
                    try { stmt.execute("ALTER TABLE IF EXISTS account ADD COLUMN IF NOT EXISTS " + col); } catch (Exception ignored) {}
                }
            } catch (Exception e) {
                System.err.println(">>> [DataInitializer] Schema migration notice: " + e.getMessage());
            }

            // 2. Check if samkimchheng exists, if not restore from data_dump.sql
            boolean needRestore = false;
            try {
                needRestore = accountRepository.findByUsername("samkimchheng").isEmpty();
            } catch (Exception e) {
                System.err.println(">>> [DataInitializer] Query failed, will trigger restore: " + e.getMessage());
                needRestore = true;
            }

            if (needRestore) {
                System.out.println(">>> [DataInitializer] Restoring full database for samkimchheng and all teachers...");
                try (Connection conn = dataSource.getConnection();
                     Statement stmt = conn.createStatement()) {
                    stmt.execute("DROP ALL OBJECTS");
                } catch (Exception e) {
                    System.err.println(">>> [DataInitializer] Notice dropping objects: " + e.getMessage());
                }

                try {
                    ResourceDatabasePopulator populator = new ResourceDatabasePopulator();
                    populator.addScript(new ClassPathResource("data_dump.sql"));
                    populator.setContinueOnError(true);
                    populator.setIgnoreFailedDrops(true);
                    populator.execute(dataSource);
                    System.out.println(">>> [DataInitializer] Full database successfully restored!");
                    try (Connection conn = dataSource.getConnection();
                         Statement stmt = conn.createStatement()) {
                        try {
                            stmt.execute("CREATE TABLE IF NOT EXISTS \"PUBLIC\".\"CERTIFICATE_RECORDS\"(" +
                                    "\"ID\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, " +
                                    "\"STUDENT_ID\" BIGINT NOT NULL, " +
                                    "\"CLASS_NAME\" VARCHAR(100), " +
                                    "\"SERIAL_NUMBER\" VARCHAR(255) UNIQUE, " +
                                    "\"SCHOOL_NAME\" VARCHAR(500), " +
                                    "\"SUBJECT_NAME\" VARCHAR(255), " +
                                    "\"PROVINCE\" VARCHAR(255), " +
                                    "\"TEACHER_NAME\" VARCHAR(255), " +
                                    "\"ROLE_SIGNER_LEFT\" VARCHAR(255), " +
                                    "\"ROLE_SIGNER_RIGHT\" VARCHAR(255), " +
                                    "\"ISSUE_DATE_KHMER\" VARCHAR(255), " +
                                    "\"ISSUE_DATE_EN\" VARCHAR(255), " +
                                    "\"UPDATED_AT\" TIMESTAMP)");
                        } catch (Exception ignored) {}
                        String[] profileCols = {
                            "ACTIVE BOOLEAN DEFAULT TRUE",
                            "GENDER VARCHAR(255)",
                            "SCHOOL_NAME VARCHAR(255)",
                            "SUBJECT VARCHAR(255)",
                            "PROVINCE VARCHAR(255)",
                            "PHONE VARCHAR(255)",
                            "TELEGRAM VARCHAR(255)",
                            "EMAIL VARCHAR(255)",
                            "POSITION VARCHAR(255)",
                            "TEACHING_CLASSES VARCHAR(255)",
                            "BIO VARCHAR(1000)"
                        };
                        for (String col : profileCols) {
                            try { stmt.execute("ALTER TABLE IF EXISTS \"ACCOUNT\" ADD COLUMN IF NOT EXISTS " + col); } catch (Exception ignored) {}
                            try { stmt.execute("ALTER TABLE IF EXISTS account ADD COLUMN IF NOT EXISTS " + col); } catch (Exception ignored) {}
                        }
                    } catch (Exception ignored) {}
                } catch (Exception e) {
                    System.err.println(">>> [DataInitializer] Error restoring database: " + e.getMessage());
                }
            }

            // 3. Ensure all lessons are set to គ្រប់ថ្នាក់ so all classes can access them
            try (Connection conn = dataSource.getConnection();
                 Statement stmt = conn.createStatement()) {
                stmt.executeUpdate("UPDATE lessons SET class_name = 'គ្រប់ថ្នាក់' WHERE class_name = '១០A' OR class_name = '10A'");
            } catch (Exception ignored) {}

            // 4. Update any default 'Administrator' or generic names to real teacher 'សំ គឹមឆេង'
            try (Connection conn = dataSource.getConnection();
                 Statement stmt = conn.createStatement()) {
                stmt.executeUpdate("UPDATE \"ACCOUNT\" SET full_name = 'សំ គឹមឆេង' WHERE full_name = 'Administrator' OR (username = 'admin' AND (full_name IS NULL OR full_name = '' OR full_name = 'Administrator'))");
                stmt.executeUpdate("UPDATE account SET full_name = 'សំ គឹមឆេង' WHERE full_name = 'Administrator' OR (username = 'admin' AND (full_name IS NULL OR full_name = '' OR full_name = 'Administrator'))");
                stmt.executeUpdate("UPDATE \"CERTIFICATE_RECORDS\" SET teacher_name = 'លោកគ្រូ សំ គឹមឆេង' WHERE teacher_name LIKE '%Administrator%' OR teacher_name LIKE '%admin%'");
                stmt.executeUpdate("UPDATE certificate_records SET teacher_name = 'លោកគ្រូ សំ គឹមឆេង' WHERE teacher_name LIKE '%Administrator%' OR teacher_name LIKE '%admin%'");
            } catch (Exception ignored) {}
        };
    }
}
